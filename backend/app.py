"""Placement Tracker backend.

Flask + SQLAlchemy. SQLite by default for local development,
PostgreSQL when DATABASE_URL points at Postgres (see config.py).

Authentication: register/login return a JWT. All application
endpoints require a token and only ever return the calling user's
own applications. The predictor endpoint is public, because it
takes no personal data and returns only a model estimate — but in
the frontend it sits behind the login screen like everything else.

Model: a single sklearn Pipeline (scaling + model) saved by
ml/train.py to backend/model.pkl. The pipeline expects a DataFrame
with the 6 synthetic-data features, in this order:
  cgpa, internships, projects, dsa_score,
  communication_score, backlogs

Run locally:
    pip install -r requirements.txt
    python app.py

Run in production (see README):
    gunicorn -w 2 -b 0.0.0.0:$PORT app:app
"""

import functools
import logging
import os

import joblib
from flask import Flask, g, jsonify, request
from sqlalchemy import create_engine, func
from sqlalchemy.orm import sessionmaker

from auth import check_password, create_token, decode_token, hash_password
from config import Config
from models import Application, Base, User

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

STATUSES = ["Applied", "Shortlisted", "Interview", "Offer", "Rejected"]
TYPES = ["Job", "Internship"]

# (field, min, max) for numeric predictor inputs.
PREDICT_RANGES = {
    "cgpa": (0, 10),
    "internships": (0, 10),
    "projects": (0, 20),
    "dsa_score": (0, 100),
    "communication_score": (0, 100),
    "backlogs": (0, 10),
}

MODEL_NOTE = (
    "Estimate from a model trained on synthetic data generated by "
    "ml/generate_data.py. It is not a guarantee of placement, and it "
    "does not use company, role, or interview performance — those "
    "factors are not in the training data."
)


def _engine():
    url = Config.DATABASE_URL
    connect_args = {"check_same_thread": False} if url.startswith("sqlite") else {}
    return create_engine(url, connect_args=connect_args)


def create_app():
    Config.check()
    app = Flask(__name__)
    engine = _engine()
    Base.metadata.create_all(engine)
    Session = sessionmaker(bind=engine)
    app.config["session_factory"] = Session
    app.config["model_path"] = Config.MODEL_PATH
    app.config["model"] = None

    # ---- helpers -------------------------------------------------

    def get_db():
        if "db" not in g:
            g.db = Session()
        return g.db

    @app.teardown_appcontext
    def close_db(_error):
        db = g.pop("db", None)
        if db is not None:
            db.close()

    def require_auth(view):
        @functools.wraps(view)
        def wrapped(*args, **kwargs):
            header = request.headers.get("Authorization", "")
            if not header.startswith("Bearer "):
                return jsonify({"error": "authentication required"}), 401
            try:
                payload = decode_token(header[7:], Config.JWT_SECRET)
                g.user_id = int(payload["sub"])
            except Exception:
                return jsonify({"error": "invalid or expired token"}), 401
            return view(*args, **kwargs)

        return wrapped

    def load_model():
        if app.config["model"] is None:
            path = app.config["model_path"]
            if not os.path.exists(path):
                return None
            app.config["model"] = joblib.load(path)
        return app.config["model"]

    @app.after_request
    def add_cors_headers(response):
        origin = request.headers.get("Origin", "")
        if origin in Config.CORS_ORIGINS:
            response.headers["Access-Control-Allow-Origin"] = origin
            response.headers["Vary"] = "Origin"
        response.headers["Access-Control-Allow-Headers"] = "Content-Type, Authorization"
        response.headers["Access-Control-Allow-Methods"] = "GET, POST, PUT, DELETE, OPTIONS"
        return response

    # ---- health --------------------------------------------------

    @app.route("/api/health")
    def health():
        return jsonify(
            {"status": "ok", "model_loaded": os.path.exists(app.config["model_path"])}
        )

    # ---- auth ----------------------------------------------------

    @app.route("/api/auth/register", methods=["POST", "OPTIONS"])
    def register():
        if request.method == "OPTIONS":
            return jsonify({}), 200
        data = request.get_json(silent=True) or {}
        email = str(data.get("email", "")).strip().lower()
        password = str(data.get("password", ""))
        if "@" not in email or "." not in email:
            return jsonify({"error": "a valid email is required"}), 400
        if len(password) < 8:
            return jsonify({"error": "password must be at least 8 characters"}), 400
        db = get_db()
        if db.query(User).filter_by(email=email).first():
            return jsonify({"error": "email already registered"}), 409
        user = User(email=email, password_hash=hash_password(password))
        db.add(user)
        db.commit()
        return jsonify({"id": user.id, "email": user.email}), 201

    @app.route("/api/auth/login", methods=["POST", "OPTIONS"])
    def login():
        if request.method == "OPTIONS":
            return jsonify({}), 200
        data = request.get_json(silent=True) or {}
        email = str(data.get("email", "")).strip().lower()
        password = str(data.get("password", ""))
        db = get_db()
        user = db.query(User).filter_by(email=email).first()
        if user is None or not check_password(password, user.password_hash):
            return jsonify({"error": "invalid email or password"}), 401
        token = create_token(user.id, Config.JWT_SECRET, Config.JWT_EXPIRY_HOURS)
        return jsonify({"token": token, "email": user.email})

    @app.route("/api/auth/me")
    @require_auth
    def me():
        db = get_db()
        user = db.query(User).filter_by(id=g.user_id).first()
        if user is None:
            return jsonify({"error": "user not found"}), 404
        return jsonify({"id": user.id, "email": user.email})

    # ---- applications (authenticated, per-user) ------------------

    def validate_application(data, partial=False):
        errors = []
        for field in ("company", "role"):
            if not partial or field in data:
                if not str(data.get(field, "")).strip():
                    errors.append(f"{field} is required")
        if "status" in data and data["status"] not in STATUSES:
            errors.append(f"status must be one of: {', '.join(STATUSES)}")
        if "type" in data and data["type"] not in TYPES:
            errors.append(f"type must be one of: {', '.join(TYPES)}")
        return errors

    @app.route("/api/stats")
    @require_auth
    def stats():
        db = get_db()
        base = db.query(Application).filter_by(user_id=g.user_id)
        total = base.count()
        by_status = {
            status: base.filter_by(status=status).count() for status in STATUSES
        }
        return jsonify({"total": total, "by_status": by_status, "offers": by_status["Offer"]})

    @app.route("/api/applications", methods=["GET", "POST", "OPTIONS"])
    @require_auth
    def applications():
        if request.method == "OPTIONS":
            return jsonify({}), 200
        db = get_db()
        if request.method == "GET":
            status = request.args.get("status", "")
            if status and status not in STATUSES:
                return jsonify({"error": "invalid status filter"}), 400
            query = db.query(Application).filter_by(user_id=g.user_id)
            if status:
                query = query.filter_by(status=status)
            rows = query.order_by(Application.id.desc()).all()
            return jsonify([row.to_dict() for row in rows])

        data = request.get_json(silent=True) or {}
        errors = validate_application(data)
        if errors:
            return jsonify({"errors": errors}), 400
        row = Application(
            user_id=g.user_id,
            company=str(data["company"]).strip(),
            role=str(data["role"]).strip(),
            type=data.get("type", "Job"),
            status=data.get("status", "Applied"),
            applied_date=str(data.get("applied_date", "")),
            notes=str(data.get("notes", "")),
        )
        db.add(row)
        db.commit()
        return jsonify(row.to_dict()), 201

    @app.route("/api/applications/<int:application_id>", methods=["GET", "PUT", "DELETE", "OPTIONS"])
    @require_auth
    def single_application(application_id):
        if request.method == "OPTIONS":
            return jsonify({}), 200
        db = get_db()
        # Filter by user_id as well as id, so one user can never
        # read, edit, or delete another user's application (404, not 403,
        # so ownership is not leaked either).
        row = (
            db.query(Application)
            .filter_by(id=application_id, user_id=g.user_id)
            .first()
        )
        if row is None:
            return jsonify({"error": "application not found"}), 404
        if request.method == "GET":
            return jsonify(row.to_dict())
        if request.method == "DELETE":
            db.delete(row)
            db.commit()
            return jsonify({"deleted": application_id})
        data = request.get_json(silent=True) or {}
        errors = validate_application(data, partial=True)
        if errors:
            return jsonify({"errors": errors}), 400
        for field in ("company", "role", "type", "status", "applied_date", "notes"):
            if field in data:
                setattr(row, field, str(data[field]).strip() if field in ("company", "role") else data[field])
        db.commit()
        return jsonify(row.to_dict())

    # ---- predictor (public, model estimate only) -----------------

    @app.route("/api/predict", methods=["POST", "OPTIONS"])
    def predict():
        if request.method == "OPTIONS":
            return jsonify({}), 200
        model = load_model()
        if model is None:
            return jsonify({"error": "model not trained yet. Run ml/train.py first."}), 503
        data = request.get_json(silent=True) or {}
        errors = []
        values = {}
        for field, (low, high) in PREDICT_RANGES.items():
            if field not in data:
                errors.append(f"{field} is required")
                continue
            try:
                value = float(data[field])
            except (TypeError, ValueError):
                errors.append(f"{field} must be a number")
                continue
            if not (low <= value <= high):
                errors.append(f"{field} must be between {low} and {high}")
            values[field] = value
        if errors:
            return jsonify({"errors": errors}), 400

        # The saved pipeline expects a DataFrame with the original
        # column names, in the order used during training. Backlogs
        # and the counts are integers in the training data, so cast
        # them back to int here.
        import pandas as pd

        frame = pd.DataFrame(
            [
                {
                    "cgpa": values["cgpa"],
                    "internships": int(values["internships"]),
                    "projects": int(values["projects"]),
                    "dsa_score": values["dsa_score"],
                    "communication_score": values["communication_score"],
                    "backlogs": int(values["backlogs"]),
                }
            ]
        )
        probability = float(model.predict_proba(frame)[0][1])
        band = "Low" if probability < 0.35 else "Moderate" if probability <= 0.65 else "Strong"
        return jsonify(
            {
                "probability": round(probability, 4),
                "percentage": round(probability * 100, 1),
                "band": band,
                "note": MODEL_NOTE,
            }
        )

    return app


app = create_app()

if __name__ == "__main__":
    # Development server only. Use gunicorn in production (see README).
    app.run(host="127.0.0.1", port=Config.PORT, debug=False)
